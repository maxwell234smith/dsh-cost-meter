/** 已发布年份中出现的全部节假日日期，便于 O(1) 查询。 */
export const HOLIDAY_SET = new Set(
  Object.values(HOLIDAY_DATA).flatMap((year) => year.holidays),
)

/** 已发布年份中的全部调休上班日。 */
export const MAKEUP_WORKDAY_SET = new Set(
  Object.values(HOLIDAY_DATA).flatMap((year) => year.makeupWorkdays),
)

/**
 * 某个年份的节假日数据是否已发布。
 * @param {number} year 公历年（北京时间的年份）。
 * @returns {boolean} true 表示该年数据已收录。
 */
export function isYearPublished(year) {
  return HOLIDAY_DATA[year]?.published === true
}
